import '../models/song.dart';

/// Metadata-only safeguard. YouTube does not expose a reliable AI-generation
/// flag; avoid rejecting ordinary songs just because their name contains "AI".
bool isLikelyAiSong(Song song) {
  if (song.source == TrackSource.localDevice) return false;
  final text = '${song.title} ${song.artist} ${song.subtitle ?? ''}';
  return RegExp(
    r'\b(ai generated|ai-generated|ai cover|ai voice|ai vocals|ai singer|sung by ai|generated by ai|artificial intelligence (cover|song|vocals)|voice clone|ai music)\b',
    caseSensitive: false,
  ).hasMatch(text);
}

List<Song> withoutAiSongs(Iterable<Song> songs) =>
    songs.where((song) => !isLikelyAiSong(song)).toList();
